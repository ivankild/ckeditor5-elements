import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defineConfig, type DefaultTheme, type HeadConfig } from 'vitepress';
import { sourceAliases } from '../../scripts/packages.js';

// The site is published on GitHub Pages, at https://ivankild.github.io/ckeditor5-elements/.
const BASE = '/ckeditor5-elements/';
const SITE = `https://ivankild.github.io${BASE}`;
const TITLE = 'CKEditor 5 Elements';
const DESCRIPTION =
	'Element-first WYSIWYG editing for CKEditor 5: customize CKEditor 5 with element commands, menus, toolbars and a ' +
	'JSON element schema, for structured content and XML, such as DocBook XML and DITA XML.';
const KEYWORDS =
	'CKEditor 5, CKEditor 5 customization, CKEditor 5 plugins, WYSIWYG editor, WYSIWYG XML editor, XML editor, ' +
	'structured content, element schema, DocBook XML, DITA XML';

// Generated by TypeDoc (`pnpm api`).
const apiSidebarFile = fileURLToPath(new URL('../api/typedoc-sidebar.json', import.meta.url));
const apiSidebar: DefaultTheme.SidebarItem[] = existsSync(apiSidebarFile)
	? (JSON.parse(readFileSync(apiSidebarFile, 'utf8')) as DefaultTheme.SidebarItem[])
	: [];

export default defineConfig({
	lang: 'en-US',
	title: TITLE,
	description: DESCRIPTION,
	base: BASE,
	// From `public/`. Links in `head` do not get the base.
	head: [
		['link', { rel: 'icon', type: 'image/svg+xml', href: `${BASE}favicon.svg` }],
		['meta', { name: 'keywords', content: KEYWORDS }],
		['meta', { property: 'og:type', content: 'website' }],
		['meta', { property: 'og:site_name', content: TITLE }],
		['meta', { name: 'twitter:card', content: 'summary' }]
	],
	cleanUrls: true,
	// The redirect from the old address of the full example is not a page of its own.
	sitemap: { hostname: SITE, transformItems: items => items.filter(item => item.url !== 'example') },
	// The canonical address of each page, and what a link to it shows when shared: its title and its description.
	transformPageData(pageData, { siteConfig }) {
		// A page can name its canonical address, e.g. a redirect the page it goes to.
		const path =
			(pageData.frontmatter.canonical as string | undefined) ??
			pageData.relativePath.replace(/(^|\/)index\.md$/, '$1').replace(/\.md$/, '');
		const url = `${SITE}${path}`;
		const title = pageData.title && pageData.title !== TITLE ? `${pageData.title} | ${TITLE}` : TITLE;
		const description = (pageData.frontmatter.description as string | undefined) ?? siteConfig.site.description;
		const head: HeadConfig[] = [
			['link', { rel: 'canonical', href: url }],
			['meta', { property: 'og:url', content: url }],
			['meta', { property: 'og:title', content: title }],
			['meta', { property: 'og:description', content: description }]
		];

		pageData.frontmatter.head = [...((pageData.frontmatter.head as HeadConfig[] | undefined) ?? []), ...head];
	},
	themeConfig: {
		nav: [
			{ text: 'Guide', link: '/guide/getting-started' },
			{ text: 'Examples', link: '/examples/' },
			{ text: 'API', link: '/api/' }
		],
		sidebar: {
			// The groups follow the packages: the core, the actions, the menus, the interaction, the schema.
			'/guide/': [
				{
					text: 'Guide',
					items: [
						{ text: 'Getting started', link: '/guide/getting-started' },
						{ text: 'Commands', link: '/guide/commands' }
					]
				},
				{
					text: 'Element actions',
					items: [
						{ text: 'Actions', link: '/guide/actions' },
						{ text: 'Clipboard', link: '/guide/clipboard' },
						{ text: 'Attributes', link: '/guide/attributes' }
					]
				},
				{
					text: 'Menus',
					items: [
						{ text: 'Context menu', link: '/guide/context-menu' },
						{ text: 'Breadcrumbs', link: '/guide/breadcrumbs' },
						{ text: 'Quick insert', link: '/guide/quick-insert' }
					]
				},
				{
					text: 'Interaction',
					items: [
						{ text: 'Selectable elements', link: '/guide/selectable' },
						{ text: 'Clickable elements', link: '/guide/clickable' },
						{ text: 'Element toolbar', link: '/guide/toolbar' }
					]
				},
				{
					text: 'Element schema',
					items: [
						{ text: 'Element schema', link: '/guide/schema' },
						{ text: 'Converters', link: '/guide/schema-converters' },
						{ text: 'Commands and buttons', link: '/guide/schema-commands' },
						{ text: 'Examples', link: '/guide/schema-examples' }
					]
				}
			],
			'/examples/': [
				{
					text: 'Examples',
					items: [
						{ text: 'Full example', link: '/examples/' },
						{ text: 'DocBook XML', link: '/examples/docbook' },
						{ text: 'DITA XML', link: '/examples/dita' }
					]
				}
			],
			'/api/': [{ text: 'API reference', items: apiSidebar }]
		},
		socialLinks: [{ icon: 'github', link: 'https://github.com/ivankild/ckeditor5-elements' }],
		outline: [2, 3],
		search: { provider: 'local' }
	},
	vite: {
		build: {
			// CKEditor's styles use CSS nesting, so keep it instead of transforming it for older browsers.
			cssTarget: ['chrome120', 'edge120', 'firefox120', 'safari17'],
			// CKEditor is a large chunk; the demos load it only when they are shown.
			chunkSizeWarningLimit: 3000
		},
		resolve: {
			// The demos use the sources of the packages.
			alias: sourceAliases()
		}
	}
});
