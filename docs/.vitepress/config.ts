import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defineConfig, type DefaultTheme } from 'vitepress';

const PACKAGES = [
	'ckeditor5-elements-core',
	'ckeditor5-elements',
	'ckeditor5-elements-breadcrumbs',
	'ckeditor5-elements-clipboard',
	'ckeditor5-elements-actions',
	'ckeditor5-elements-toolbar',
	'ckeditor5-elements-example',
	'ckeditor5-elements-context-menu',
	'ckeditor5-elements-quick-insert'
];

// The site is published on GitHub Pages, at https://ivankild.github.io/ckeditor5-elements/.
const BASE = '/ckeditor5-elements/';

const resolvePackage = (name: string): string =>
	fileURLToPath(new URL(`../../packages/${name}/src/index.ts`, import.meta.url));

// Generated by TypeDoc (`pnpm api`).
const apiSidebarFile = fileURLToPath(new URL('../api/typedoc-sidebar.json', import.meta.url));
const apiSidebar: DefaultTheme.SidebarItem[] = existsSync(apiSidebarFile)
	? (JSON.parse(readFileSync(apiSidebarFile, 'utf8')) as DefaultTheme.SidebarItem[])
	: [];

export default defineConfig({
	title: 'CKEditor 5 Elements',
	description:
		'Element commands, context menu, clipboard, actions, toolbars, quick insert and breadcrumbs for CKEditor 5.',
	base: BASE,
	// From `public/`. Links in `head` do not get the base.
	head: [['link', { rel: 'icon', type: 'image/svg+xml', href: `${BASE}favicon.svg` }]],
	cleanUrls: true,
	themeConfig: {
		nav: [
			{ text: 'Guide', link: '/guide/getting-started' },
			{ text: 'Example', link: '/example' },
			{ text: 'API', link: '/api/' }
		],
		sidebar: {
			'/guide/': [
				{
					text: 'Guide',
					items: [
						{ text: 'Getting started', link: '/guide/getting-started' },
						{ text: 'Commands', link: '/guide/commands' },
						{ text: 'Context menu', link: '/guide/context-menu' },
						{ text: 'Clipboard', link: '/guide/clipboard' },
						{ text: 'Actions', link: '/guide/actions' },
						{ text: 'Element toolbar', link: '/guide/toolbar' },
						{ text: 'Quick insert', link: '/guide/quick-insert' },
						{ text: 'Breadcrumbs', link: '/guide/breadcrumbs' }
					]
				}
			],
			'/api/': [{ text: 'API reference', items: apiSidebar }]
		},
		socialLinks: [{ icon: 'github', link: 'https://github.com/ivankild/ckeditor5-elements' }],
		outline: [2, 3],
		search: { provider: 'local' }
	},
	vite: {
		build: {
			// CKEditor's styles use CSS nesting, so keep it instead of transforming it for older browsers.
			cssTarget: ['chrome120', 'edge120', 'firefox120', 'safari17'],
			// CKEditor is a large chunk; the demos load it only when they are shown.
			chunkSizeWarningLimit: 3000
		},
		resolve: {
			// The demos use the sources of the packages. Exact matches only, so `<package>/index.css` still resolves.
			alias: PACKAGES.map(name => ({ find: new RegExp(`^${name}$`), replacement: resolvePackage(name) }))
		}
	}
});
